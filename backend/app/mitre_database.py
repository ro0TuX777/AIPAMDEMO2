def validate_technique_id(technique_id: str) -> Tuple[bool, Optional[str]]:
    """
    Validate a MITRE ATT&CK technique ID and return the correct name.

    Args:
        technique_id: The technique ID to validate (e.g., "T1071", "T1071.001")

    Returns:
        Tuple of (is_valid, technique_name or None)
    """
    if technique_id in MITRE_TECHNIQUES:
        return True, MITRE_TECHNIQUES[technique_id]
    return False, None


def get_technique_name(technique_id: str) -> str:
    """
    Get the name for a MITRE ATT&CK technique ID.

    Args:
        technique_id: The technique ID (e.g., "T1071")

    Returns:
        The technique name, or "Unknown Technique" if not found
    """
    return MITRE_TECHNIQUES.get(technique_id, "Unknown Technique")


def validate_and_fix_technique(technique_id: str, provided_name: str) -> Tuple[str, str, bool]:
    """
    Validate a technique and fix the name if the ID is valid but name is wrong.

    Args:
        technique_id: The MITRE technique ID
        provided_name: The name that was provided with the technique

    Returns:
        Tuple of (technique_id, corrected_name, was_corrected)
    """
    is_valid, correct_name = validate_technique_id(technique_id)

    if is_valid:
        if provided_name != correct_name:
            return technique_id, correct_name, True
        return technique_id, provided_name, False

    # ID not found - return as-is but mark for review
    return technique_id, provided_name, False


def get_all_techniques() -> Dict[str, str]:
    """Return all MITRE ATT&CK techniques."""
    return MITRE_TECHNIQUES.copy()


def search_techniques(query: str) -> Dict[str, str]:
    """
    Search for techniques by name or ID.

    Args:
        query: Search query (case-insensitive)

    Returns:
        Dict of matching technique_id -> name
    """
    query_lower = query.lower()
    return {
        tid: name
        for tid, name in MITRE_TECHNIQUES.items()
        if query_lower in tid.lower() or query_lower in name.lower()
    }

